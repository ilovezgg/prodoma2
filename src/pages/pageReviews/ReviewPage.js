const Reviews = () => {
  const [current, setCurrent] = useState(0);
  const [animDir, setAnimDir] = useState(null);

  const goTo = useCallback((index, dir) => {
    setAnimDir(dir);
    setTimeout(() => {
      setCurrent(index);
      setAnimDir(null);
    }, 350);
  }, []);

  const prev = () => {
    const index = (current - 1 + REVIEWS.length) % REVIEWS.length;
    goTo(index, 'left');
  };

  const next = useCallback(() => {
    const index = (current + 1) % REVIEWS.length;
    goTo(index, 'right');
  }, [current, goTo]);



  const review = REVIEWS[current];
  const [expanded, setExpanded] = useState(false);


  useEffect(() => { setExpanded(false); }, [current]);

  return (
    <section className={z.section}>
      <div className={z.header}>
        <div className={z.label}>Отзывы клиентов</div>
        <h2 className={z.title}>142 семьи уже живут<br />в своём доме</h2>
      </div>

      <div className={z.slider}>
        
        <div className={z.imageWrap}>
          <div className={`${z.imageInner} ${animDir === 'right' ? z.slideOutLeft : animDir === 'left' ? z.slideOutRight : ''}`}>
            <Image
              src={review.image}
              alt={review.name}
              fill
              style={{ objectFit: 'cover' }}
              priority
            />
            <div className={z.projectBadge}>{review.project}</div>
          </div>
        </div>

   
        <div className={z.content}>
          <div className={`${z.contentInner} ${animDir === 'right' ? z.fadeOutLeft : animDir === 'left' ? z.fadeOutRight : z.fadeIn}`}>
            <div className={z.quote}>«</div>
            <div className={`${z.reviewTextWrap} ${expanded ? z.reviewTextExpanded : ''}`}>
              <p className={z.reviewText}>{review.text}</p>
              {!expanded && <div className={z.fadeGradient} />}
            </div>
            <button className={z.expandBtn} onClick={() => setExpanded((v) => !v)}>
              {expanded ? 'Свернуть ↑' : 'Читать полностью ↓'}
            </button>
            <div className={z.author}>
              <div className={z.authorName}>{review.name}</div>
              <div className={z.authorMeta}> · {review.year}</div>
            </div>
          </div>

       
          <div className={z.nav}>
            <button className={z.navBtn} onClick={prev}>←</button>
            <div className={z.dots}>
              {REVIEWS.map((_, i) => (
                <button
                  key={i}
                  className={`${z.dot} ${i === current ? z.dotActive : ''}`}
                  onClick={() => goTo(i, i > current ? 'right' : 'left')}
                />
              ))}
            </div>
            <button className={z.navBtn} onClick={next}>→</button>
          </div>
        </div>
      </div>
    </section>
  );
};

export default Reviews;