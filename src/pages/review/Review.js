const ReviewCard = ({ review, isLarge }) => {
  const [isOpen, setIsOpen] = useState(false);

  return (
    <div className={`${z.card} ${isLarge ? z.cardLarge : ''}`}>
      <div className={z.imageWrap}>
        <img src={review.img} alt={`Дом ${review.name}`} className={z.image} />
        {review.link && (
          <a href={review.link} target="_blank" rel="noopener noreferrer" className={z.yandexBtn}>
            Читать на Яндекс.Картах →
          </a>
        )}
      </div>
      <div className={z.content}>
        <div className={z.name}>{review.name}</div>
        <div className={z.text}>
          {isOpen || !review.collapsible ? review.text : review.short}
        </div>
        {review.collapsible && (
          <button 
            className={z.readMore} 
            onClick={() => setIsOpen(!isOpen)}
            aria-expanded={isOpen}
          >
            {isOpen ? 'Свернуть' : 'Читать полностью'}
          </button>
        )}
      </div>
    </div>
  );
};

